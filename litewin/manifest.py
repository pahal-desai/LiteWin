import json
import os
import platform
import shutil
import time

from litewin import version


def toolversions():
    tools = {
        "python": platform.python_version(),
        "platform": platform.platform(),
    }
    for name in ["xorriso", "wimlib-imagex", "7zz", "7z", "dism"]:
        p = shutil.which(name) or os.path.expanduser(f"~/.local/bin/{name}")
        tools[name] = p if os.path.isfile(p) and os.access(p, os.X_OK) else "not found"
    return tools


def create(data):
    # assembles complete build manifest
    stamp = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    def_removed = any(a.get("id") == "WindowsDefender" for a in data.get("removals", []))
    manifest = {
        "litewin version": version,
        "build time": stamp,
        "original iso": data.get("iso", {}),
        "windows image": data.get("image", {}),
        "profile": data.get("profile", "standard"),
        "components removed": data.get("removals", []),
        "components retained": data.get("retained", []),
        "privacy settings": data.get("privacy", []),
        "firefox integration": data.get("firefox", {"enabled": True}),
        "security status": {
            "windows defender": "disabled / removed" if def_removed else "preserved",
            "windows update": "preserved",
            "windows firewall": "preserved",
            "smartscreen": "preserved",
            "uac": "preserved",
        },
        "tools": toolversions(),
        "warnings": data.get("warnings", []),
        "errors": data.get("errors", []),
    }
    return manifest


def markdown(manifest):
    # formats human-readable Markdown audit report
    iso_info = manifest.get("original iso", {})
    img_info = manifest.get("windows image", {})
    sec_info = manifest.get("security status", {})
    tools = manifest.get("tools", {})

    lines = [
        f"# LiteWin Build & Audit Report",
        "",
        f"> Generated by LiteWin v{manifest.get('litewin version')} on {manifest.get('build time')}",
        "",
        "## 1. Source Image Details",
        "",
        f"- **ISO Path:** `{iso_info.get('iso path', 'N/A')}`",
        f"- **ISO SHA-256:** `{iso_info.get('sha256', 'N/A')}`",
        f"- **Edition:** {img_info.get('name', 'N/A')} ({img_info.get('edition', 'N/A')})",
        f"- **Build Number:** `{img_info.get('build', 'N/A')}`",
        f"- **Architecture:** `{img_info.get('architecture', 'N/A')}`",
        "",
        "## 2. Security & System Integrity",
        "",
        "LiteWin preserves essential system update capabilities and documents all security service changes:",
        "",
        "| Component | Status | Rationale |",
        "| :--- | :--- | :--- |",
        f"| Windows Defender | {sec_info.get('windows defender', 'preserved').title()} | {'Disabled to minimize background CPU/RAM footprint' if 'disabled' in sec_info.get('windows defender', '') else 'Essential anti-malware and kernel protection'} |",
        "| Windows Update | Preserved | Ongoing security updates and bug fixes |",
        "| Windows Firewall | Preserved | Inbound/outbound traffic filtering |",
        "| SmartScreen | Preserved | Malicious download protection |",
        "| User Account Control (UAC) | Preserved | Privilege escalation guard |",
        "",
        "## 3. Customizations Applied",
        "",
        f"### Removed Applications ({len(manifest.get('components removed', []))})",
        "",
        "| Application | Package ID | Rationale |",
        "| :--- | :--- | :--- |",
    ]

    for app in manifest.get("components removed", []):
        lines.append(
            f"| {app.get('name', 'N/A')} | `{app.get('id', 'N/A')}` | {app.get('reason', 'N/A')} |"
        )

    lines.extend([
        "",
        f"### Retained Essential Applications ({len(manifest.get('components retained', []))})",
        "",
        "| Application | Package ID | Rationale |",
        "| :--- | :--- | :--- |",
    ])

    for app in manifest.get("components retained", []):
        lines.append(
            f"| {app.get('name', 'N/A')} | `{app.get('id', 'N/A')}` | {app.get('reason', 'N/A')} |"
        )

    lines.extend([
        "",
        f"### Privacy & Telemetry Settings ({len(manifest.get('privacy settings', []))})",
        "",
        "| Setting | Hive / Key | Value | Configured Value |",
        "| :--- | :--- | :--- | :--- |",
    ])

    for s in manifest.get("privacy settings", []):
        lines.append(
            f"| {s.get('name', 'N/A')} | `{s.get('hive', '')}` | `{s.get('value', '')}` | `{s.get('data', '')}` |"
        )

    ff = manifest.get("firefox integration", {})
    lines.extend([
        "",
        "## 4. Firefox Integration",
        "",
        f"- **Status:** {'Enabled' if ff.get('enabled') else 'Disabled'}",
        "- **Telemetry Opt-Out:** Configured via enterprise `policies.json`",
        "- **Default Browser:** Configured via OEM `AppAssoc.xml` (`http`, `https`, `.html`, `.htm`)",
        "",
        "## 5. Build Environment Tools",
        "",
        f"- **Python:** {tools.get('python', 'N/A')}",
        f"- **Host Platform:** {tools.get('platform', 'N/A')}",
        f"- **xorriso:** `{tools.get('xorriso', 'N/A')}`",
        f"- **wimlib-imagex:** `{tools.get('wimlib-imagex', 'N/A')}`",
        f"- **7-Zip:** `{tools.get('7zz', tools.get('7z', 'N/A'))}`",
        "",
    ])

    warnings = manifest.get("warnings", [])
    if warnings:
        lines.append("## Build Warnings")
        lines.append("")
        for w in warnings:
            lines.append(f"- ⚠️ {w}")
        lines.append("")

    return "\n".join(lines)


def save(manifest, outdir):
    os.makedirs(outdir, exist_ok=True)
    jsonpath = os.path.join(outdir, "manifest.json")
    mdpath = os.path.join(outdir, "audit_report.md")

    with open(jsonpath, "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2)

    with open(mdpath, "w", encoding="utf-8") as f:
        f.write(markdown(manifest))

    return {
        "manifest": jsonpath,
        "report": mdpath,
    }
