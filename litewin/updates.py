def makescript():
    # generates PowerShell script to permanently disable Windows Update services and tasks
    lines = [
        "# LiteWin Windows Update Permanent Disablement Script",
        "$ErrorActionPreference = 'SilentlyContinue'",
        "",
        "Write-Output '[LiteWin] Permanently disabling Windows Update...'",
        "",
        "# 1. Stop and disable Windows Update services",
        "$wuServices = @('wuauserv', 'UsoSvc', 'WaaSMedicSvc', 'dosvc')",
        "foreach ($svc in $wuServices) {",
        "    Stop-Service -Name $svc -Force -ErrorAction SilentlyContinue",
        "    Set-Service -Name $svc -StartupType Disabled -ErrorAction SilentlyContinue",
        "    reg add \"HKLM\\SYSTEM\\CurrentControlSet\\Services\\$svc\" /v Start /t REG_DWORD /d 4 /f | Out-Null",
        "}",
        "",
        "# 2. Disable all Windows Update scheduled tasks",
        "$wuTaskPaths = @(",
        "    '\\Microsoft\\Windows\\WindowsUpdate\\*',",
        "    '\\Microsoft\\Windows\\UpdateOrchestrator\\*',",
        "    '\\Microsoft\\Windows\\WaaSMedic\\*'",
        ")",
        "foreach ($path in $wuTaskPaths) {",
        "    Get-ScheduledTask -TaskPath $path -ErrorAction SilentlyContinue | Disable-ScheduledTask -ErrorAction SilentlyContinue",
        "}",
        "",
        "# 3. Group Policy registry locks",
        "$wuPolicies = @(",
        "    @{ Path = 'HKLM:\\SOFTWARE\\Policies\\Microsoft\\Windows\\WindowsUpdate\\AU'; Name = 'NoAutoUpdate'; Type = 'DWord'; Value = 1 },",
        "    @{ Path = 'HKLM:\\SOFTWARE\\Policies\\Microsoft\\Windows\\WindowsUpdate\\AU'; Name = 'AUOptions'; Type = 'DWord'; Value = 1 },",
        "    @{ Path = 'HKLM:\\SOFTWARE\\Policies\\Microsoft\\Windows\\WindowsUpdate'; Name = 'SetDisableUXWUAccess'; Type = 'DWord'; Value = 1 },",
        "    @{ Path = 'HKLM:\\SOFTWARE\\Policies\\Microsoft\\Windows\\WindowsUpdate'; Name = 'DisableWindowsUpdateAccess'; Type = 'DWord'; Value = 1 },",
        "    @{ Path = 'HKLM:\\SOFTWARE\\Policies\\Microsoft\\Windows\\WindowsUpdate'; Name = 'ExcludeWUDriversInQualityUpdate'; Type = 'DWord'; Value = 1 },",
        "    @{ Path = 'HKLM:\\SOFTWARE\\Policies\\Microsoft\\Windows\\WindowsUpdate'; Name = 'DoNotConnectToWindowsUpdateInternetLocations'; Type = 'DWord'; Value = 1 },",
        "    @{ Path = 'HKLM:\\SOFTWARE\\Policies\\Microsoft\\Windows\\DeliveryOptimization'; Name = 'DODownloadMode'; Type = 'DWord'; Value = 0 }",
        ")",
        "foreach ($p in $wuPolicies) {",
        "    if (!(Test-Path $p.Path)) { New-Item -Path $p.Path -Force | Out-Null }",
        "    Set-ItemProperty -Path $p.Path -Name $p.Name -Type $p.Type -Value $p.Value -Force",
        "}",
        "",
        "Write-Output '[LiteWin] Windows Update permanently disabled.'",
    ]
    return "\n".join(lines)
